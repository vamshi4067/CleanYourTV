import os,shlex,subprocess,time,xml.etree.ElementTree as ET
adb=shlex.split(os.environ.get('ADB', 'adb'))
serial=os.environ.get('TV_SERIAL')
if not serial: raise SystemExit('Set TV_SERIAL to your connected test TV. This test navigates the launcher.')
adb+=['-s', serial]
def run(*args):return subprocess.check_output(adb+list(args),timeout=25)
def key(*keys):
 run('shell','input keyevent '+' '.join(keys));time.sleep(.35)
def snapshot():
 run('shell','uiautomator dump /data/local/tmp/cricket-nav.xml >/dev/null')
 return ET.fromstring(run('shell','cat /data/local/tmp/cricket-nav.xml'))
def focus():
 return next((n for n in snapshot().iter('node') if n.get('focused')=='true'),ET.Element('node'))
def expect(label):
 n=focus()
 value=' '.join([n.get('text',''),n.get('content-desc',''),n.get('resource-id','')])
 assert label.casefold() in value.casefold(),(label,value)
def expect_category(label):
 n=focus()
 assert label in n.get('content-desc',''),(label,n.attrib)
def home():
 key('HOME');time.sleep(1)
def shortcuts():
 key('DPAD_DOWN');key('DPAD_CENTER')
run('shell','input keyevent WAKEUP; am force-stop com.gathin.tvhome; am start -W -a android.intent.action.MAIN -c android.intent.category.HOME -n com.gathin.tvhome/.MainActivity >/dev/null')
time.sleep(4);home()
key(*(['DPAD_LEFT']*12));expect('NETFLIX')
key('DPAD_RIGHT','DPAD_RIGHT');expect('prime video')
key('DPAD_LEFT');expect('YouTube')
key(*(['DPAD_RIGHT']*12));expect('aha')
key('DPAD_UP');expect('btnSettings')
key('DPAD_LEFT');expect('btnWifi')
key('DPAD_LEFT','DPAD_LEFT');expect('btnInputs')
key('BACK');expect('aha')
print('PASS dock and top-button navigation',flush=True)
key('DPAD_DOWN');expect('Shortcuts')
key('DPAD_LEFT','DPAD_RIGHT');expect('Shortcuts')
key('DPAD_CENTER');key('DPAD_LEFT');expect('More apps')
key(*(['DPAD_RIGHT']*5));expect('Watch Later')
key('BACK');expect('Shortcuts')
key('BACK');expect('aha')
print('PASS shortcut edges and Back levels',flush=True)
shortcuts();key('DPAD_RIGHT');key('DPAD_CENTER')
key('BACK','DPAD_RIGHT');expect('Pick something')
print('PASS rapid Back then Right after Favourites',flush=True)
key('DPAD_CENTER');expect_category('Cricket')
key('DPAD_RIGHT','DPAD_RIGHT');expect_category('Hindi movies')
key('DPAD_LEFT','DPAD_LEFT');expect_category('Cricket')
key('DPAD_LEFT');expect_category('Anything at all')
key('DPAD_RIGHT');expect_category('Cricket')
print('PASS rapid two-way category navigation and wrap',flush=True)
key('DPAD_UP');expect('Add more')
key('DPAD_CENTER');key('DPAD_DOWN');expect('Lucky Baskhar')
key('DPAD_RIGHT','DPAD_RIGHT');expect('HIT: The Third Case')
key('DPAD_LEFT','DPAD_LEFT','DPAD_LEFT');expect('Lucky Baskhar')
key('BACK');expect('Add more')
key('BACK','DPAD_RIGHT');expect('Match Day')
key('DPAD_RIGHT');expect('Watch Later')
key('DPAD_CENTER')
key(*(['DPAD_LEFT']*5+['DPAD_RIGHT']*5))
n=focus()
assert not n.get('resource-id','').endswith(('btnSettings','btnWifi','btnInputs'))
